"""Migrations stay in sync with app/models.py.

Each test builds a throw-away database next to DATABASE_URL (skipped if the DB user cannot CREATE DATABASE),
so CI fails as soon as someone edits models.py without generating a migration.
"""

from __future__ import annotations

import os
import uuid

import pytest
from alembic import command
from alembic.autogenerate import compare_metadata
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from sqlalchemy import Column, MetaData, String, create_engine, inspect, text
from sqlalchemy.engine import make_url

from app.init_db import alembic_config, init
from app.models import Base


@pytest.fixture()
def scratch_url():
    url = make_url(os.environ["DATABASE_URL"])
    name = f"mig_test_{uuid.uuid4().hex[:10]}"
    admin = create_engine(url.set(database="postgres"), isolation_level="AUTOCOMMIT")
    try:
        with admin.connect() as c:
            c.execute(text(f'CREATE DATABASE "{name}"'))
    except Exception as e:  # noqa: BLE001
        pytest.skip(f"cannot create a scratch database: {e}")
    yield url.set(database=name)
    with admin.connect() as c:
        c.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
    admin.dispose()


def _run(url, fn, *args):
    engine = create_engine(url)
    with engine.begin() as conn:
        cfg = alembic_config()
        cfg.attributes["connection"] = conn
        fn(cfg, *args)
    engine.dispose()


def test_single_head():
    heads = ScriptDirectory.from_config(alembic_config()).get_heads()
    assert len(heads) == 1, f"multiple alembic heads, merge them: {heads}"


def test_upgrade_matches_models_and_downgrade_is_clean(scratch_url):
    _run(scratch_url, command.upgrade, "head")
    _run(scratch_url, command.check)  # raises AutogenerateDiffsDetected if models.py drifted

    _run(scratch_url, command.downgrade, "base")
    engine = create_engine(scratch_url)
    with engine.connect() as c:
        assert set(inspect(c).get_table_names()) <= {"alembic_version"}
        assert c.scalar(text("SELECT count(*) FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace "
                             "WHERE n.nspname = 'public' AND t.typtype = 'e'")) == 0
        assert c.scalar(text("SELECT count(*) FROM pg_sequences WHERE schemaname = 'public'")) == 0
    engine.dispose()
    _run(scratch_url, command.upgrade, "head")  # and back up again


def test_autogenerate_detects_model_changes(scratch_url):
    _run(scratch_url, command.upgrade, "head")
    changed = MetaData(naming_convention=Base.metadata.naming_convention)
    for table in Base.metadata.tables.values():
        table.to_metadata(changed)
    changed.tables["candidates_profile"].append_column(Column("line_id", String(50)))
    engine = create_engine(scratch_url)
    with engine.connect() as c:
        diff = compare_metadata(MigrationContext.configure(c), changed)
    engine.dispose()
    assert [(d[0], d[2], d[3].name) for d in diff if d[0] == "add_column"] == [("add_column", "candidates_profile", "line_id")]


def test_init_db_builds_and_seeds_a_fresh_database(scratch_url):
    init(scratch_url.render_as_string(hide_password=False))
    init(scratch_url.render_as_string(hide_password=False))  # idempotent
    engine = create_engine(scratch_url)
    with engine.connect() as c:
        assert c.scalar(text("SELECT count(*) FROM prefectures")) == 47
        assert c.scalar(text("SELECT count(*) FROM roles")) == 5
        assert c.scalar(text("SELECT version_num FROM alembic_version")) is not None
    engine.dispose()


def test_init_db_refuses_unbaselined_legacy_database(scratch_url):
    engine = create_engine(scratch_url)
    with engine.begin() as c:
        c.execute(text("CREATE EXTENSION IF NOT EXISTS pg_trgm"))
        c.execute(text("CREATE SEQUENCE job_code_seq START 1000"))
    Base.metadata.create_all(engine)  # simulates a pre-Alembic database
    engine.dispose()
    with pytest.raises(SystemExit, match="alembic stamp head"):
        init(scratch_url.render_as_string(hide_password=False))
